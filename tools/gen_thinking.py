#!/usr/bin/env python3
"""Generate plugin/core/thinking_data.go.
Input 1: oh-my-pi baked catalog dump (/tmp/omp_models.json, from tools/omp_dump.ts over
  packages/catalog/src/models.json of github.com/can1357/oh-my-pi, MIT).
Input 2: CLIProxyAPI v8.0.48 internal/registry/models/models.json (MIT) for the levels CPA accepts."""
import json,sys
OMP_COMMIT=sys.argv[1]; CPA=sys.argv[2]
PROVS=['google-antigravity','openai-codex','openai','xai','commandcode','opencode-go','anthropic','google','deepseek','moonshot','zai','kimi-code','minimax','openrouter']
d=json.load(open('/tmp/omp_models.json'))
rows={}
for x in d:
    if x['p'] not in PROVS or not x.get('reasoning') or not x.get('th'): continue
    t=x['th']; ef=t.get('efforts') or []
    if not ef: continue
    rows.setdefault(x['p'],{})[x['id']]=(ef,t.get('defaultLevel') or '',t.get('mode') or '')
cpa=json.load(open(CPA))
chan={'antigravity':'antigravity','codex-pro':'codex','xai':'xai','claude':'claude','gemini':'gemini','kimi':'kimi'}
lv={}
for ch,name in chan.items():
    for m in cpa[ch]:
        t=m.get('thinking')
        if t is None: lv.setdefault(name,{})[m['id']]=None
        else: lv.setdefault(name,{})[m['id']]=[l for l in (t.get('levels') or []) if l not in ('none','auto')] or ['*budget*']
q=lambda s:json.dumps(s)
o=['// Code generated by tools/gen_thinking.py; DO NOT EDIT.','//',
 '// ompThinking is a subset of oh-my-pi\'s baked per-model thinking table',
 '// (packages/catalog/src/models.json, built from compat/rules/**/*.kdl),',
 '// https://github.com/can1357/oh-my-pi commit '+OMP_COMMIT+'.',
 '// oh-my-pi is MIT licensed: Copyright (c) 2025-2026 Can Bölük, Copyright (c) 2026 Stencil Labs, Inc.',
 '// cpaLevels lists the thinking levels CLIProxyAPI v8.0.48 registers per model',
 '// (internal/registry/models/models.json, MIT, router-for-me/CLIProxyAPI).',
 '// "*budget*" = budget-only model: CPA converts any level to a token budget.','',
 'package core','','var ompThinking = map[string]map[string]ompRow{']
for p in PROVS:
    if p not in rows: continue
    o.append('\t%s: {'%q(p))
    for i,(ef,df,md) in sorted(rows[p].items()):
        o.append('\t\t%s: {Efforts: []string{%s}, Default: %s, Mode: %s},'%(q(i),', '.join(map(q,ef)),q(df),q(md)))
    o.append('\t},')
o+=['}','','var cpaLevels = map[string]map[string][]string{']
for p,m in sorted(lv.items()):
    o.append('\t%s: {'%q(p))
    for i,l in sorted(m.items()):
        o.append('\t\t%s: %s,'%(q(i),'nil' if l is None else '{'+', '.join(map(q,l))+'}'))
    o.append('\t},')
o.append('}')
open('core/thinking_data.go','w').write('\n'.join(o)+'\n')
print(sum(len(v) for v in rows.values()), sum(len(v) for v in lv.values()))
